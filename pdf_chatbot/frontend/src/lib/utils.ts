import { clsx, type ClassValue } from "clsx";
import { twMerge } from "tailwind-merge";
import { AnalysisCardData } from "@/types/analysis";
import { ChatMessage } from "@/types/chat";

export function cn(...inputs: ClassValue[]) {
  return twMerge(clsx(inputs));
}

export function formatBytes(bytes: number, decimals = 1): string {
  if (bytes === 0) return "0 Bytes";
  const k = 1024;
  const dm = decimals < 0 ? 0 : decimals;
  const sizes = ["Bytes", "KB", "MB", "GB"];
  const i = Math.floor(Math.log(bytes) / Math.log(k));
  return `${parseFloat((bytes / Math.pow(k, i)).toFixed(dm))} ${sizes[i]}`;
}

export function exportDocumentAnalysisMarkdown(
  analysis: AnalysisCardData,
  chatHistory: ChatMessage[]
): string {
  let md = `# Document Analysis Report: ${analysis.metadata.document_title}\n\n`;
  md += `**Filename:** \`${analysis.metadata.filename}\` | **Type:** ${analysis.metadata.document_type} | **Pages:** ${analysis.metadata.page_count}\n\n`;
  md += `---\n\n## Executive Summary\n\n${analysis.executive_summary}\n\n`;

  md += `## Key Takeaways\n\n`;
  analysis.key_points.forEach((kp) => {
    md += `- **[${kp.category || "General"}]** ${kp.point}\n`;
  });
  md += `\n`;

  if (analysis.outline && analysis.outline.length > 0) {
    md += `## Table of Contents & Structure\n\n`;
    analysis.outline.forEach((item) => {
      const indent = "  ".repeat(Math.max(0, item.level - 1));
      md += `${indent}- ${item.title} *(Page ${item.page_number})*\n`;
    });
    md += `\n`;
  }

  if (analysis.entities && analysis.entities.length > 0) {
    md += `## Key Entities\n\n`;
    const grouped: Record<string, string[]> = {};
    analysis.entities.forEach((ent) => {
      if (!grouped[ent.category]) grouped[ent.category] = [];
      grouped[ent.category].push(ent.name);
    });
    for (const [category, names] of Object.entries(grouped)) {
      md += `- **${category}:** ${names.join(", ")}\n`;
    }
    md += `\n`;
  }

  if (analysis.tables && analysis.tables.length > 0) {
    md += `## Extracted Tabular Data\n\n`;
    analysis.tables.forEach((t) => {
      md += `### ${t.caption || `Table on Page ${t.page_number}`}\n\n`;
      if (t.headers.length > 0) {
        md += `| ${t.headers.join(" | ")} |\n`;
        md += `| ${t.headers.map(() => "---").join(" | ")} |\n`;
        t.rows.forEach((r) => {
          md += `| ${r.join(" | ")} |\n`;
        });
        md += `\n`;
      }
    });
  }

  if (chatHistory && chatHistory.length > 0) {
    md += `## Grounded Q&A Transcript\n\n`;
    chatHistory.forEach((msg) => {
      if (msg.role === "user") {
        md += `### Question:\n${msg.content}\n\n`;
      } else if (msg.role === "assistant") {
        md += `### Grounded Answer:\n${msg.content}\n\n`;
        if (msg.citations && msg.citations.length > 0) {
          md += `*Sources Used: ${msg.citations.map((c) => c.label).join(", ")}*\n\n`;
        }
      }
    });
  }

  md += `---\n*Generated by PDF Analysis Chatbot | Grounded Document Intelligence*\n`;
  return md;
}
